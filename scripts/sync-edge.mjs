// Copies the shared table engine into the poker-table edge function (Deno needs explicit .ts imports).
import { readFileSync, writeFileSync } from 'node:fs';
for (const f of ['cards', 'holdem', 'tableops']) {
  const src = readFileSync(`src/engine/${f}.ts`, 'utf8').replace(/from '\.\/(\w+)'/g, "from './$1.ts'");
  writeFileSync(`supabase/functions/poker-table/${f}.ts`, `// Generated by scripts/sync-edge.mjs from src/engine/${f}.ts. Do not edit here.\n${src}`);
}
console.log('synced cards, holdem, tableops into supabase/functions/poker-table');
